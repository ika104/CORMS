import { StatusBadgeTone } from '../components/common/StatusBadge';

export type TaskType = 'To Do' | 'Follow-up Task' | 'Reminder';
export type TaskPriority = 'Low' | 'Normal' | 'High';
export type TaskStatus = 'Pending' | 'In Progress' | 'Overdue' | 'Completed';

/** A person assigned through CORMS_Tasks.AssignedToUser. The SharePoint column permits multiple
 * people, so task views should use this collection rather than treating the field as one string. */
export interface ITaskAssignee {
  /** SharePoint site-user id, when returned by the person-field expansion. */
  id?: number;
  displayName: string;
  email?: string;
}

export interface ITask {
  id: string;
  subject: string;
  type: TaskType;
  priority: TaskPriority;
  status: TaskStatus;
  /** SharePoint's built-in Created timestamp — used to keep the newest tasks first. */
  createdAt?: string;
  dueDate: string;
  /** A comma-separated display value retained for search, tables, and CSV export. */
  assignee: string;
  /** Every person selected in CORMS_Tasks.AssignedToUser, in SharePoint's stored order. */
  assignees: ITaskAssignee[];
  hasAttachment: boolean;
  isMine: boolean;
  isOverdue: boolean;
  /** CORMS_Tasks.ReferenceNo (CMS-049 AC6) — the task's own reference series, populated
   * independently of CORMS_Correspondence.ReferenceNo; generated by Power Apps at task-creation
   * time (out of this task's scope — see TaskListServiceCore.ts). Optional: absent on the
   * pre-existing mock dataset, which predates this field. */
  referenceNo?: string;
  /** CORMS_Tasks.AssignedToTeam (Text, e.g. a department name) — drives the "Team Tasks" tile.
   * Optional: absent on the pre-existing mock dataset. */
  team?: string;
  /** True when `team` matches the current user's own CORMS_UserRoles.Department — precomputed by
   * TaskListServiceCore (live) alongside `isMine`/`isOverdue`, same "one predicate object drives
   * both tile count and grid filter" pattern as My Correspondence's tiles. Always false/undefined
   * on the mock dataset (no department concept there). */
  isMyTeam?: boolean;
  /** CORMS_Tasks.RelatedCorrespondenceId — optional cross-reference to a CORMS_Correspondence
   * item, populated by Power Apps (out of this task's scope). */
  relatedCorrespondenceId?: string;
  /** CORMS_Tasks.Description. */
  description?: string;
}

export interface ITaskBadgeConfig {
  labelKey: string;
  tone: StatusBadgeTone;
}

// Client feedback ("too much colour") — Type and Status are drawn as plain labels (neutral tone,
// no pill), mirroring Status/Security on the correspondence cards. Only Priority keeps its coloured
// tones so High/Normal still read as a flag at a glance.
export const TASK_TYPE_CONFIG: Record<TaskType, ITaskBadgeConfig> = {
  'To Do': { labelKey: 'myTasks.type.toDo', tone: 'neutral' },
  'Follow-up Task': { labelKey: 'myTasks.type.followUp', tone: 'neutral' },
  Reminder: { labelKey: 'myTasks.type.reminder', tone: 'neutral' },
};

// Priority keeps its colours (the one flag the client asked to preserve). Low uses the green
// "success" tone so it reads as a filled pill like Normal (blue) and High (red) — 'neutral' would
// render it as a plain label, since neutral is now the app's "no colour" tag treatment.
export const TASK_PRIORITY_CONFIG: Record<TaskPriority, ITaskBadgeConfig> = {
  Low: { labelKey: 'myTasks.priority.low', tone: 'success' },
  Normal: { labelKey: 'myTasks.priority.normal', tone: 'info' },
  High: { labelKey: 'myTasks.priority.high', tone: 'danger' },
};

export const TASK_STATUS_CONFIG: Record<TaskStatus, ITaskBadgeConfig> = {
  Pending: { labelKey: 'myTasks.status.pending', tone: 'neutral' },
  'In Progress': { labelKey: 'myTasks.status.inProgress', tone: 'neutral' },
  Overdue: { labelKey: 'myTasks.status.overdue', tone: 'neutral' },
  Completed: { labelKey: 'myTasks.status.completed', tone: 'neutral' },
};

// The union types are only as trustworthy as the source list: the values arrive from a
// SharePoint choice column, so anything added there lands here as an unmapped string. Fall
// back to the raw value (an unknown i18n key resolves to itself) with a neutral tone rather
// than dereferencing undefined and taking the whole grid down — same guard STATUS_CONFIG
// gets in MyCorrespondenceView.
function resolveBadgeConfig<K extends string>(map: Record<K, ITaskBadgeConfig>, key: K): ITaskBadgeConfig {
  return map[key] ?? { labelKey: key, tone: 'neutral' };
}

export const taskTypeConfig = (type: TaskType): ITaskBadgeConfig =>
  resolveBadgeConfig(TASK_TYPE_CONFIG, type);
export const taskPriorityConfig = (priority: TaskPriority): ITaskBadgeConfig =>
  resolveBadgeConfig(TASK_PRIORITY_CONFIG, priority);
export const taskStatusConfig = (status: TaskStatus): ITaskBadgeConfig =>
  resolveBadgeConfig(TASK_STATUS_CONFIG, status);
